function showQuestion() {

    const question =
        currentSector.questions[currentQuestion];

    selectedAnswer = null;
    answered = false;


    feedback.style.display = "none";
    feedback.className = "feedback";


    nextBtn.disabled = true;
    nextBtn.textContent = "تأكيد الإجابة";


    questionNumber.textContent =
        "السؤال " +
        (currentQuestion + 1) +
        " من 4";


    questionText.textContent =
        question.question;


    answersContainer.innerHTML = "";


    // إنشاء الاختيارات

    question.answers.forEach(function(answer, index) {

        const answerElement =
            document.createElement("div");

        answerElement.className = "answer";


        // أ - ب - ج - د

        const letters = ["أ", "ب", "ج", "د"];

        answerElement.textContent =
            letters[index] + ") " + answer;


        // عند الضغط على الاختيار

        answerElement.addEventListener("click", function() {

            if (answered) {
                return;
            }


            // إزالة التحديد القديم

            document.querySelectorAll(".answer").forEach(function(item) {

                item.classList.remove("selected");

            });


            // تحديد الاختيار

            answerElement.classList.add("selected");

            selectedAnswer = index;

            nextBtn.disabled = false;

        });


        answersContainer.appendChild(answerElement);

    });


    // تحديث شريط التقدم

    const progress =
        ((currentQuestion + 1) / 4) * 100;

    progressBar.style.width =
        progress + "%";

}


